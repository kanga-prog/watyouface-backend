-- WatYouFace production baseline.
-- This migration is for new, empty PostgreSQL databases only. It contains no
-- accounts, credentials, demo wallets, or other seed data.

CREATE TABLE contract (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255),
    content VARCHAR(5000),
    version VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    accepted_contract BOOLEAN NOT NULL DEFAULT FALSE,
    avatar_url VARCHAR(255),
    role VARCHAR(255) NOT NULL DEFAULT 'USER',
    contract_id BIGINT,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT fk_users_contract FOREIGN KEY (contract_id) REFERENCES contract (id)
);

CREATE TABLE user_contract (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    contract_id BIGINT,
    accepted BOOLEAN NOT NULL DEFAULT FALSE,
    accepted_at TIMESTAMP(6),
    CONSTRAINT fk_user_contract_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_contract_contract FOREIGN KEY (contract_id) REFERENCES contract (id),
    CONSTRAINT uq_user_contract_user_contract UNIQUE (user_id, contract_id)
);

CREATE TABLE video (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255),
    url VARCHAR(255),
    uploaded_at TIMESTAMP(6),
    uploader_id BIGINT,
    CONSTRAINT fk_video_uploader FOREIGN KEY (uploader_id) REFERENCES users (id)
);

CREATE TABLE post (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(255),
    image_url VARCHAR(255),
    video_url VARCHAR(255),
    created_at TIMESTAMP(6),
    author_id BIGINT,
    CONSTRAINT fk_post_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_group BOOLEAN NOT NULL DEFAULT FALSE,
    title VARCHAR(255),
    created_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE conversation_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_conversation_users_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id),
    CONSTRAINT fk_conversation_users_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_conversation_users_participant UNIQUE (conversation_id, user_id)
);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    content VARCHAR(2000),
    sent_at TIMESTAMP(6) WITH TIME ZONE,
    edited BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id),
    CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id) REFERENCES users (id),
    CONSTRAINT fk_messages_receiver FOREIGN KEY (receiver_id) REFERENCES users (id)
);

CREATE TABLE comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6),
    author_id BIGINT NOT NULL,
    post_id BIGINT,
    video_id BIGINT,
    CONSTRAINT fk_comment_author FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT fk_comment_post FOREIGN KEY (post_id) REFERENCES post (id),
    CONSTRAINT fk_comment_video FOREIGN KEY (video_id) REFERENCES video (id),
    CONSTRAINT ck_comment_target CHECK (
        (CASE WHEN post_id IS NULL THEN 0 ELSE 1 END + CASE WHEN video_id IS NULL THEN 0 ELSE 1 END) = 1
    )
);

CREATE TABLE likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    post_id BIGINT,
    video_id BIGINT,
    CONSTRAINT fk_likes_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_likes_post FOREIGN KEY (post_id) REFERENCES post (id),
    CONSTRAINT fk_likes_video FOREIGN KEY (video_id) REFERENCES video (id),
    CONSTRAINT ck_likes_target CHECK (
        (CASE WHEN post_id IS NULL THEN 0 ELSE 1 END + CASE WHEN video_id IS NULL THEN 0 ELSE 1 END) = 1
    ),
    CONSTRAINT uq_likes_user_post UNIQUE (user_id, post_id),
    CONSTRAINT uq_likes_user_video UNIQUE (user_id, video_id)
);

CREATE TABLE listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(2000),
    price DOUBLE PRECISION NOT NULL,
    image VARCHAR(255),
    status VARCHAR(255) NOT NULL DEFAULT 'AVAILABLE',
    seller_id BIGINT NOT NULL,
    buyer_id BIGINT,
    CONSTRAINT fk_listings_seller FOREIGN KEY (seller_id) REFERENCES users (id),
    CONSTRAINT fk_listings_buyer FOREIGN KEY (buyer_id) REFERENCES users (id),
    CONSTRAINT ck_listings_price CHECK (price > 0),
    CONSTRAINT ck_listings_status CHECK (status IN ('AVAILABLE', 'PENDING', 'ACCEPTED', 'PAID', 'SHIPPED', 'RECEIVED', 'REFUSED'))
);

CREATE TABLE wallet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    balance DOUBLE PRECISION NOT NULL DEFAULT 0,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_wallet_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_wallet_user UNIQUE (user_id),
    CONSTRAINT ck_wallet_balance CHECK (balance >= 0)
);

CREATE TABLE transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount DOUBLE PRECISION NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'CREATED',
    from_user_id BIGINT NOT NULL,
    to_user_id BIGINT NOT NULL,
    listing_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_transaction_from_user FOREIGN KEY (from_user_id) REFERENCES users (id),
    CONSTRAINT fk_transaction_to_user FOREIGN KEY (to_user_id) REFERENCES users (id),
    CONSTRAINT fk_transaction_listing FOREIGN KEY (listing_id) REFERENCES listings (id),
    CONSTRAINT uq_transaction_listing_id UNIQUE (listing_id),
    CONSTRAINT ck_transaction_amount CHECK (amount > 0),
    CONSTRAINT ck_transaction_status CHECK (status IN ('CREATED', 'SUCCESS', 'FAILED', 'COMPLETED'))
);

CREATE TABLE video_share (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT,
    sender_id BIGINT,
    receiver_id BIGINT,
    seen BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_video_share_video FOREIGN KEY (video_id) REFERENCES video (id),
    CONSTRAINT fk_video_share_sender FOREIGN KEY (sender_id) REFERENCES users (id),
    CONSTRAINT fk_video_share_receiver FOREIGN KEY (receiver_id) REFERENCES users (id)
);

CREATE INDEX idx_post_created_at ON post (created_at DESC);
CREATE INDEX idx_comment_post_created_at ON comment (post_id, created_at);
CREATE INDEX idx_messages_conversation_sent_at ON messages (conversation_id, sent_at DESC);
CREATE INDEX idx_conversation_users_user ON conversation_users (user_id);
CREATE INDEX idx_listings_status ON listings (status);
CREATE INDEX idx_listings_seller ON listings (seller_id);
CREATE INDEX idx_listings_buyer ON listings (buyer_id);
CREATE INDEX idx_transaction_from_user ON transaction (from_user_id);
CREATE INDEX idx_transaction_to_user ON transaction (to_user_id);
CREATE INDEX idx_video_share_receiver ON video_share (receiver_id);
